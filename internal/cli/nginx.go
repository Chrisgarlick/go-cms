// nginxSite is what the nginx server block is generated from.
type nginxSite struct {
	Name        string   // the site's name (several sites on one server), or ""
	Hosts       []string // every host it answers; the first is canonical
	Root        string   // pre-rendered pages: <data>/public/<host>
	MediaDir    string   // <data>/media (empty: media is on its own origin)
	CSP         string   // the public pages' Content-Security-Policy
	Slash       bool     // trailing_slash: URLs end in /
	Upstream    string   // file holding the active colour's proxy_pass line
	MaxUploadMB int
	TLS         bool // Let's Encrypt certificates at /etc/letsencrypt/live/<host>/
}

// The headers Go sets on every response (web.SecurityHeaders), repeated for
// files nginx serves itself: an add_header in a location replaces the
// server's, so each static location lists them all.
var nginxSecurity = []string{
	`Strict-Transport-Security "max-age=63072000; includeSubDomains"`,
	`X-Content-Type-Options "nosniff"`,
	`Referrer-Policy "strict-origin-when-cross-origin"`,
	`Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"`,
	`Cross-Origin-Opener-Policy "same-origin"`,
}

func nginxHeaders(b *strings.Builder, indent string, extra ...string) {
	for _, h := range append(append([]string{}, nginxSecurity...), extra...) {
		fmt.Fprintf(b, "%sadd_header %s always;\n", indent, h)
	}
}

// nginxConfig renders the server blocks for a site (spec 9.5): pages and
// assets straight from disk, everything else, and every request with a
// query string, to the active colour through the upstream include.
func nginxConfig(s nginxSite) string {
	host := s.Hosts[0]
	var b strings.Builder
	label := host
	if s.Name != "" {
		label = s.Name + " (" + host + ")"
	}
	fmt.Fprintf(&b, "# Generated by `cms nginx` (cms %s) for %s.\n", versionString(), label)
	fmt.Fprintf(&b, "# Deploys rewrite only %s; regenerate this file when hosts or paths change.\n\n", s.Upstream)
	tls := func(indent string) {
		if !s.TLS {
			return
		}
		fmt.Fprintf(&b, "%sssl_certificate /etc/letsencrypt/live/%s/fullchain.pem;\n", indent, host)
		fmt.Fprintf(&b, "%sssl_certificate_key /etc/letsencrypt/live/%s/privkey.pem;\n", indent, host)
		fmt.Fprintf(&b, "%sssl_protocols TLSv1.2 TLSv1.3;\n%sssl_session_cache shared:cms_ssl:10m;\n", indent, indent)
	}
	listen := "listen 80;\n\tlisten [::]:80;"
	if s.TLS {
		listen = "listen 443 ssl http2;\n\tlisten [::]:443 ssl http2;"
		fmt.Fprintf(&b, "server {\n\tlisten 80;\n\tlisten [::]:80;\n\tserver_name %s;\n", strings.Join(s.Hosts, " "))
		fmt.Fprintf(&b, "\tlocation /.well-known/acme-challenge/ {\n\t\troot /var/www/html;\n\t}\n")
		fmt.Fprintf(&b, "\tlocation / {\n\t\treturn 301 https://%s$request_uri;\n\t}\n}\n\n", host)
	}
	if len(s.Hosts) > 1 {
		fmt.Fprintf(&b, "server {\n\t%s\n\tserver_name %s;\n", listen, strings.Join(s.Hosts[1:], " "))
		tls("\t")
		fmt.Fprintf(&b, "\treturn 308 https://%s$request_uri;\n}\n\n", host)
	}
	fmt.Fprintf(&b, "server {\n\t%s\n\tserver_name %s;\n", listen, host)
	tls("\t")
	fmt.Fprintf(&b, "\tserver_tokens off;\n\troot %s;\n\tclient_max_body_size %dm;\n", s.Root, s.MaxUploadMB)
	fmt.Fprintf(&b, "\tcharset utf-8;\n\tgzip on;\n\tgzip_types text/css application/javascript application/json application/xml application/atom+xml image/svg+xml text/plain;\n\n")
	fmt.Fprintf(&b, "\t# Go answers anything not on disk, dynamic routes and every request with a\n\t# query string (redirect rules can match ?category=, ?page= and so on).\n")
	fmt.Fprintf(&b, "\terror_page 418 = @cms;\n\n")
	fmt.Fprintf(&b, "\tlocation @cms {\n\t\tinclude %s;\n", s.Upstream)
	fmt.Fprintf(&b, "\t\tproxy_http_version 1.1;\n\t\tproxy_set_header Connection \"\";\n\t\tproxy_set_header Host $host;\n")
	fmt.Fprintf(&b, "\t\tproxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n\t\tproxy_set_header X-Forwarded-Proto $scheme;\n\t\tproxy_set_header X-Real-IP $remote_addr;\n")
	fmt.Fprintf(&b, "\t\tproxy_read_timeout 120s;\n\t\tproxy_request_buffering off;\n\t}\n\n")
	fmt.Fprintf(&b, "\tlocation ~ ^/(admin|api|forms|preview|search)(/|$) {\n\t\treturn 418;\n\t}\n")
	fmt.Fprintf(&b, "\tlocation = /healthz {\n\t\treturn 418;\n\t}\n\tlocation = /readyz {\n\t\treturn 418;\n\t}\n\n")
	if s.MediaDir != "" {
		fmt.Fprintf(&b, "\t# Media variants and files (originals of images are never public).\n\tlocation ^~ /media/ {\n")
		fmt.Fprintf(&b, "\t\talias %s/;\n", filepath.Join(s.MediaDir, "public"))
		nginxHeaders(&b, "\t\t", `Cache-Control "public, max-age=31536000, immutable"`,
			`Content-Security-Policy "default-src 'none'; img-src 'self'; media-src 'self'; sandbox"`)
		fmt.Fprintf(&b, "\t\ttry_files $uri =404;\n\t}\n\n")
	}
	fmt.Fprintf(&b, "\t# Fingerprinted theme assets.\n\tlocation ^~ /assets/ {\n\t\tgzip_static on;\n")
	nginxHeaders(&b, "\t\t", `Cache-Control "public, max-age=31536000, immutable"`)
	fmt.Fprintf(&b, "\t\ttry_files $uri @cms;\n\t}\n\n")
	if !s.Slash {
		fmt.Fprintf(&b, "\t# URLs have no trailing slash: /about/ reaches Go, which redirects it.\n\tlocation ~ ^/.+/$ {\n\t\treturn 418;\n\t}\n\n")
	}
	fmt.Fprintf(&b, "\t# Pre-rendered pages, feeds and the sitemap: from disk without touching Go.\n\tlocation / {\n")
	fmt.Fprintf(&b, "\t\tif ($args != \"\") {\n\t\t\treturn 418;\n\t\t}\n\t\tgzip_static on;\n")
	nginxHeaders(&b, "\t\t", fmt.Sprintf("Content-Security-Policy %q", s.CSP), `Cache-Control "public, max-age=0, must-revalidate"`)
	if s.Slash {
		fmt.Fprintf(&b, "\t\ttry_files $uri $uri/index.html @cms;\n\t}\n}\n")
	} else {
		fmt.Fprintf(&b, "\t\ttry_files $uri/index.html $uri @cms;\n\t}\n}\n")
	}
	return b.String()
}

// nginxCmd prints the nginx server blocks for this site. Unlike `cms caddy`
// it isn't regenerated on deploy (certbot and hand edits live in the file);
// deploy.sh only rewrites the upstream include.
func nginxCmd() *cobra.Command {
	var upstream string
	var noTLS bool
	cmd := &cobra.Command{
		Use:   "nginx",
		Short: "Print the nginx server blocks for this site (several sites on one server)",
		Long: `Prints nginx server blocks for this site: pre-rendered pages, feeds and theme
assets served from disk (gzip_static), media from the media directory, and
dynamic routes, cache misses and requests with a query string proxied to the
active colour. The active colour's address lives in an include file that
deploy.sh rewrites on each deploy (default /etc/nginx/cms/<name>-upstream.conf,
holding one line: proxy_pass http://127.0.0.1:PORT;).

TLS uses the Let's Encrypt certificate for the first host: run
"certbot certonly --nginx -d <host>" first, or pass --no-tls.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, err := loadConfig()
			if err != nil {
				return err
			}
			a, err := app.New(cmd.Context(), cfg, slog.New(slog.NewTextHandler(io.Discard, nil)), app.Options{})
			if err != nil {
				return err
			}
			defer a.Close()
			u, _ := url.Parse(cfg.BaseURL)
			host := u.Hostname()
			hosts := []string{host}
			for _, h := range cfg.Hosts {
				if h != host {
					hosts = append(hosts, h)
				}
			}
			if upstream == "" {
				name := cfg.Name
				if name == "" {
					name = "cms"
				}
				upstream = "/etc/nginx/cms/" + name + "-upstream.conf"
			}
			s := nginxSite{Name: cfg.Name, Hosts: hosts, Root: filepath.Join(cfg.PublicDir(), host), CSP: a.PublicCSP().String(),
				Slash: a.Site().Config.Slash(), Upstream: upstream, MaxUploadMB: cfg.Media.MaxUploadMB, TLS: !noTLS}
			if cfg.MediaURL == "" {
				s.MediaDir = cfg.MediaDir()
			}
			_, err = io.WriteString(os.Stdout, nginxConfig(s))
			return err
		},
	}
	cmd.Flags().StringVar(&upstream, "upstream-file", "", "include file with the active colour's proxy_pass (default /etc/nginx/cms/<name>-upstream.conf)")
	cmd.Flags().BoolVar(&noTLS, "no-tls", false, "plain HTTP on port 80 (TLS terminated elsewhere)")
	return cmd
}
