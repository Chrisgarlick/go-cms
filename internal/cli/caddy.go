package cli

import (
	"fmt"
	"io"
	"log/slog"
	"net/url"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"

	"cms/internal/app"
	"cms/internal/version"
)

// caddyCmd prints the Caddy site block for this install. The deploy script
// writes it to /etc/caddy/sites/cms.caddy, so headers for files Caddy serves
// match the ones Go sets (spec 9.5).
func caddyCmd() *cobra.Command {
	upstreamFile := "/etc/caddy/cms-upstream.caddy"
	cmd := &cobra.Command{
		Use:   "caddy",
		Short: "Print the Caddy site configuration for this install",
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, err := loadConfig()
			if err != nil {
				return err
			}
			a, err := app.New(cmd.Context(), cfg, slog.New(slog.NewTextHandler(io.Discard, nil)), app.Options{})
			if err != nil {
				return err
			}
			defer a.Close()
			u, _ := url.Parse(cfg.BaseURL)
			host := u.Hostname()
			root := filepath.Join(cfg.PublicDir(), host)
			csp := a.PublicCSP().String()
			hosts := strings.Join(cfg.Hosts, ", ")
			var b strings.Builder
			fmt.Fprintf(&b, "# Generated by `cms caddy` (cms %s). Do not edit: regenerate on deploy.\n", versionString())
			fmt.Fprintf(&b, "%s {\n", hosts)
			fmt.Fprintf(&b, "\tencode zstd gzip\n")
			fmt.Fprintf(&b, "\theader {\n\t\tStrict-Transport-Security \"max-age=63072000; includeSubDomains\"\n\t\tX-Content-Type-Options nosniff\n")
			fmt.Fprintf(&b, "\t\tReferrer-Policy strict-origin-when-cross-origin\n\t\tPermissions-Policy \"camera=(), microphone=(), geolocation=(), payment=(), usb=()\"\n")
			fmt.Fprintf(&b, "\t\tCross-Origin-Opener-Policy same-origin\n\t\t-Server\n\t}\n")
			for _, h := range cfg.Hosts {
				if h != host {
					fmt.Fprintf(&b, "\t@alias host %s\n\tredir @alias https://%s{uri} 308\n", h, host)
				}
			}
			fmt.Fprintf(&b, "\troot * %s\n\n", root)
			fmt.Fprintf(&b, "\t# Dynamic routes always reach Go.\n\t@dynamic path /admin /admin/* /api/* /forms/* /preview/* /search/* /search /healthz /readyz\n")
			fmt.Fprintf(&b, "\thandle @dynamic {\n\t\timport %s\n\t}\n\n", upstreamFile)
			if cfg.MediaURL == "" {
				fmt.Fprintf(&b, "\t# Media variants and files (originals of images are never public).\n\thandle_path /media/* {\n\t\troot * %s/public\n", cfg.MediaDir())
				fmt.Fprintf(&b, "\t\theader Cache-Control \"public, max-age=31536000, immutable\"\n\t\theader Content-Security-Policy \"default-src 'none'; img-src 'self'; media-src 'self'; sandbox\"\n")
				fmt.Fprintf(&b, "\t\tfile_server\n\t}\n\n")
			}
			fmt.Fprintf(&b, "\t# Fingerprinted theme assets.\n\t@assets path /assets/*\n\thandle @assets {\n\t\t@exists file\n\t\theader @exists Cache-Control \"public, max-age=31536000, immutable\"\n")
			fmt.Fprintf(&b, "\t\tfile_server {\n\t\t\tprecompressed br gzip\n\t\t}\n\t}\n\n")
			fmt.Fprintf(&b, "\t# Pre-rendered pages: served from disk without touching Go.\n")
			if a.Site().Config.Slash() {
				fmt.Fprintf(&b, "\t@rendered file {path}/index.html {path}\n")
				fmt.Fprintf(&b, "\thandle @rendered {\n")
			} else {
				// URLs are published without a trailing slash: /about is served from
				// about/index.html, and /about/ falls through to Go, which redirects.
				fmt.Fprintf(&b, "\t@rendered {\n\t\tfile {path}/index.html {path}\n\t\tnot path_regexp ^/.+/$\n\t}\n")
				fmt.Fprintf(&b, "\thandle @rendered {\n\t\trewrite * {file_match.relative}\n")
			}
			fmt.Fprintf(&b, "\t\theader Content-Security-Policy %q\n\t\theader Cache-Control \"public, max-age=0, must-revalidate\"\n", csp)
			fmt.Fprintf(&b, "\t\tfile_server {\n\t\t\tprecompressed br gzip\n\t\t}\n\t}\n\n")
			fmt.Fprintf(&b, "\t# Everything else (cache misses, redirects, 404s) reaches Go.\n\thandle {\n\t\timport %s\n\t}\n}\n", upstreamFile)
			if cfg.MediaURL != "" {
				mu, _ := url.Parse(cfg.MediaURL)
				fmt.Fprintf(&b, "\n%s {\n\troot * %s/public\n\theader Cache-Control \"public, max-age=31536000, immutable\"\n", mu.Host, cfg.MediaDir())
				fmt.Fprintf(&b, "\theader Content-Security-Policy \"default-src 'none'; img-src 'self'; media-src 'self'; sandbox\"\n\theader X-Content-Type-Options nosniff\n")
				fmt.Fprintf(&b, "\t@private path /private/*\n\trespond @private 404\n\tfile_server\n}\n")
			}
			_, err = io.WriteString(os.Stdout, b.String())
			return err
		},
	}
	cmd.Flags().StringVar(&upstreamFile, "upstream-file", upstreamFile, "file holding the active reverse_proxy line (rewritten by deploy.sh)")
	return cmd
}

func versionString() string { return version.Version }
